//! plan.sh: `readonly` assignments the driver sources. Values only, no logic.

use std::collections::BTreeMap;
use std::fmt::Write;

use atlas_tui::config::{DeployKind, DeployTarget};

use super::remote::shq;

pub struct Plan<'a> {
    pub app: &'a str,
    pub target_name: &'a str,
    pub target: &'a DeployTarget,
    pub dir: &'a str,
    pub release: &'a str,
    pub sha: &'a str,
    pub sha256: &'a str,
    pub user: &'a str,
    pub rollback: bool,
    pub rollback_to: &'a str,
    pub force: bool,
    pub lock_wait: u64,
}

fn arr<'s>(out: &mut String, name: &str, items: impl Iterator<Item = &'s str>) {
    let vals: Vec<String> = items.map(shq).collect();
    let _ = writeln!(out, "readonly {name}=({})", vals.join(" "));
}

pub fn render_plan(p: &Plan) -> String {
    let t = p.target;
    let hooks = t.hooks.clone().unwrap_or_default();
    let o = |s: &Option<String>| s.clone().unwrap_or_default();
    let vars: [(&str, String); 22] = [
        ("APP", p.app.into()),
        ("TARGET", p.target_name.into()),
        ("DIR", p.dir.into()),
        ("RELEASE", p.release.into()),
        ("SHA", p.sha.into()),
        ("SHA256", p.sha256.into()),
        ("DEPLOY_USER", p.user.into()),
        ("KEEP", t.keep.unwrap_or(5).to_string()),
        ("MIN_FREE_MB", t.min_free_mb.unwrap_or(1024).to_string()),
        ("HEALTH_TIMEOUT", t.health_timeout.unwrap_or(60).to_string()),
        (
            "HEALTH_PASSES",
            t.health_passes.unwrap_or(3).max(1).to_string(),
        ),
        ("SOAK", t.soak.unwrap_or(15).to_string()),
        ("PAUSE_MARKER", o(&t.pause_marker)),
        ("INSTALL", o(&t.install)),
        ("MIGRATE", o(&t.migrate)),
        ("HOOK_PRE_SWAP", o(&hooks.pre_swap)),
        ("HOOK_POST_SWAP", o(&hooks.post_swap)),
        ("HOOK_POST_DEPLOY", o(&hooks.post_deploy)),
        ("HOOK_ON_FAILURE", o(&hooks.on_failure)),
        (
            "MODE",
            if p.rollback { "rollback" } else { "deploy" }.into(),
        ),
        ("ROLLBACK_TO", p.rollback_to.into()),
        ("FORCE", if p.force { "1" } else { "" }.into()),
    ];
    let mut out = String::from("# generated by atlas deploy — do not edit\n");
    // RELEASE/SHA are reassigned by the driver in rollback/noop paths.
    for (k, v) in &vars {
        let kw = if matches!(*k, "RELEASE" | "SHA") {
            ""
        } else {
            "readonly "
        };
        let _ = writeln!(out, "{kw}{k}={}", shq(v));
    }
    let _ = writeln!(out, "readonly LOCK_WAIT={}", p.lock_wait);
    let links: BTreeMap<&String, &String> = t.link.iter().flatten().collect();
    arr(&mut out, "LINK_SRC", links.values().map(|s| s.as_str()));
    arr(&mut out, "LINK_DST", links.keys().map(|s| s.as_str()));
    let s = &t.services;
    arr(&mut out, "SVC_NAME", s.iter().map(|s| s.name.as_str()));
    arr(
        &mut out,
        "SVC_KIND",
        s.iter().map(|s| match s.kind {
            DeployKind::Systemd => "systemd",
            DeployKind::Compose => "compose",
            DeployKind::Command => "command",
        }),
    );
    arr(
        &mut out,
        "SVC_HEALTH",
        s.iter().map(|s| s.health.as_deref().unwrap_or("")),
    );
    arr(
        &mut out,
        "SVC_COMPOSE",
        s.iter().map(|s| s.compose_file.as_deref().unwrap_or("")),
    );
    arr(
        &mut out,
        "SVC_RESTART",
        s.iter().map(|s| s.restart.as_deref().unwrap_or("")),
    );
    out
}

// Runs the plan through a local bash (deploy targets are Linux servers).
#[cfg(all(test, unix))]
mod tests {
    use super::*;

    #[test]
    fn plan_is_valid_bash_and_round_trips_values() {
        let target: DeployTarget = target_fixture();
        let p = Plan {
            app: "shop",
            target_name: "prod",
            target: &target,
            dir: "/opt/shop",
            release: "20250101000000-abcdef0",
            sha: "abcdef0123",
            sha256: "00",
            user: "me@host",
            rollback: false,
            rollback_to: "",
            force: false,
            lock_wait: 0,
        };
        let plan = render_plan(&p);
        let script = format!(
            "{plan}\nprintf '%s|' \"$INSTALL\" \"${{SVC_RESTART[1]}}\" \"${{LINK_DST[0]}}\" \"$KEEP\" \"${{#SVC_NAME[@]}}\""
        );
        let out = std::process::Command::new("bash")
            .arg("-c")
            .arg(&script)
            .output()
            .unwrap();
        assert!(
            out.status.success(),
            "{}",
            String::from_utf8_lossy(&out.stderr)
        );
        assert_eq!(
            String::from_utf8_lossy(&out.stdout),
            "echo 'it''s' $(whoami)|kill -HUP 1|.env|5|2|"
        );
    }

    fn target_fixture() -> DeployTarget {
        serde_json::from_value(serde_json::json!({
            "host": "prod",
            "install": "echo 'it''s' $(whoami)",
            "link": {".env": "/opt/shop/shared/.env"},
            "services": [
                {"name": "api", "kind": "systemd", "health": "http://127.0.0.1/h"},
                {"name": "cron", "kind": "command", "restart": "kill -HUP 1"}
            ]
        }))
        .unwrap()
    }
}
