// The built-in coding agents have ONE source: crates/atlas-core/data/agents.json (Rust embeds it, Atlas Desktop
// imports it). Atlas Mobile cannot read that file at runtime, so its copy is generated here and nowhere else:
// apps/mobile/lib/core/protocol/agent_registry_data.dart. Never edit it by hand.
//
//   bun scripts/gen-agents-dart.ts            rewrite the Dart file from agents.json
//   bun scripts/gen-agents-dart.ts --check    exit 1 when the Dart file is out of date (`bun test scripts` runs this)
//   bun scripts/gen-agents-dart.ts --check --json   the same verdict as {"ok": bool, "file": ..., "fix": ...}
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const ROOT = join(import.meta.dir, "..");
export const SOURCE = "crates/atlas-core/data/agents.json";
export const OUTPUT = "apps/mobile/lib/core/protocol/agent_registry_data.dart";
export const FIX = "bun scripts/gen-agents-dart.ts";

/** What Atlas Mobile reads of an agent (a subset of the JSON: the phone launches and signs in, nothing else). */
interface Agent {
	id: string;
	label: string;
	bin: string;
	setup: string;
	can_ask: boolean;
	one_shot: string[] | null;
}

const lit = (s: string) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$")}'`;

/** The Dart source for `agents` (pure: no file access, so tests can feed it any list). */
export function render(agents: Agent[]): string {
	const rows = agents
		.map(
			(a) =>
				`  BuiltinAgent(\n    id: ${lit(a.id)},\n    label: ${lit(a.label)},\n    bin: ${lit(a.bin)},\n    setup: ${lit(a.setup)},\n    canAsk: ${a.can_ask},\n    writesCommits: ${a.one_shot !== null},\n  ),`,
		)
		.join("\n");
	return `// GENERATED by \`${FIX}\` from ${SOURCE}: do not edit.
// The built-in coding agents are listed once, in that file; \`bun test scripts\` fails when this copy is stale.

/// One built-in agent (an entry of \`agents.json\`, the fields the phone reads).
class BuiltinAgent {
  const BuiltinAgent({
    required this.id,
    required this.label,
    required this.bin,
    required this.setup,
    required this.canAsk,
    required this.writesCommits,
  });

  final String id;
  final String label;

  /// The program name on the host's \`PATH\`.
  final String bin;

  /// \`atlas setup <setup>\` installs the hooks that report its state.
  final String setup;

  /// Whether a headless crewmate of this agent can pause a tool call for approval.
  final bool canAsk;

  /// Whether it can write an AI commit message (a verified one-shot run).
  final bool writesCommits;
}

/// Every built-in agent, in display order.
const builtinAgents = <BuiltinAgent>[
${rows}
];
`;
}

export function load(): Agent[] {
	return JSON.parse(readFileSync(join(ROOT, SOURCE), "utf8"));
}

/** The committed Dart file (empty when missing). */
export function committed(): string {
	try {
		return readFileSync(join(ROOT, OUTPUT), "utf8");
	} catch {
		return "";
	}
}

/** Empty when `have` (the committed Dart file) matches `agents.json`, else one line saying what to run. */
export function drift(have = committed()): string[] {
	return have === render(load()) ? [] : [`${OUTPUT} is out of date with ${SOURCE}. Fix: ${FIX}`];
}

if (import.meta.main) {
	const args = process.argv.slice(2);
	if (args.includes("--check")) {
		const bad = drift();
		if (args.includes("--json")) {
			console.log(JSON.stringify({ ok: bad.length === 0, file: OUTPUT, fix: FIX }));
		} else if (bad.length) {
			console.error(bad.join("\n"));
		}
		process.exit(bad.length ? 1 : 0);
	}
	writeFileSync(join(ROOT, OUTPUT), render(load()));
	console.log(`wrote ${OUTPUT}`);
}
